function Format-AssignmentForPost {
    param(
        [string]$Category,
        [Parameter(Mandatory = $true)]
        $Assignment
    )

    switch ($Category) {
        "App" {
            $clean = [ordered]@{
                "@odata.type" = "#microsoft.graph.mobileAppAssignment"
                intent        = if ($Assignment.intent) { $Assignment.intent } else { "required" }
                target        = $Assignment.target
            }
            if ($null -ne $Assignment.settings) {
                $clean["settings"] = $Assignment.settings
            }
            return [PSCustomObject]$clean
        }
        "PowerShellScript" {
            return [PSCustomObject][ordered]@{
                "@odata.type" = "#microsoft.graph.deviceManagementScriptAssignment"
                target        = $Assignment.target
            }
        }
        "ProactiveRemediation" {
            $clean = [ordered]@{
                "@odata.type"        = "#microsoft.graph.deviceHealthScriptAssignment"
                target               = $Assignment.target
                runRemediationScript = [bool]$Assignment.runRemediationScript
            }
            if ($null -ne $Assignment.runSchedule) {
                $clean["runSchedule"] = $Assignment.runSchedule
            }
            return [PSCustomObject]$clean
        }
        default {
            return [PSCustomObject][ordered]@{
                target = $Assignment.target
            }
        }
    }
}

function Get-AssignmentSummaryText {
    param([array]$Assignments)
    if ($null -eq $Assignments -or $Assignments.Count -eq 0) {
        return "None (0 assignments)"
    }
    $parts = foreach ($a in $Assignments) {
        $t = $a.target
        if ($null -eq $t) { continue }
        $tType = $t.'@odata.type'
        $shortType = switch ($tType) {
            "#microsoft.graph.allDevicesAssignmentTarget"             { "AllDevices" }
            "#microsoft.graph.allLicensedUsersAssignmentTarget"       { "AllUsers" }
            "#microsoft.graph.groupAssignmentTarget"                  { "IncludeGroup($($t.groupId))" }
            "#microsoft.graph.exclusionGroupAssignmentTarget"         { "ExcludeGroup($($t.groupId))" }
            "#microsoft.graph.configurationManagerCollectionAssignmentTarget" { "Collection($($t.collectionId))" }
            default                                                   { $tType }
        }
        $fMode = $t.deviceAndAppManagementAssignmentFilterType
        $fId   = $t.deviceAndAppManagementAssignmentFilterId
        if (-not [string]::IsNullOrWhiteSpace($fMode) -and $fMode -ne "none") {
            "$shortType[Filter:$fMode=$fId]"
        }
        else {
            "$shortType[NoFilter]"
        }
    }
    return ($parts -join "; ")
}

# ============================================================================
# 3. VALIDATE BACKUP FOLDER & DISCOVER BACKUP JSON FILES
# ============================================================================
if (-not (Test-Path $BackupFolderPath)) {
    throw "Backup folder not found: $BackupFolderPath"
}

$resolvedBackupPath = (Resolve-Path $BackupFolderPath).Path
$timestamp = Get-Date -Format "yyyyMMdd_HHmmss"

if ([string]::IsNullOrWhiteSpace($OutputDirectory)) {
    $parentDir = Split-Path -Parent $resolvedBackupPath
    if ([string]::IsNullOrWhiteSpace($parentDir)) { $parentDir = $PWD.Path }
    $OutputDirectory = $parentDir
}
if (-not (Test-Path $OutputDirectory)) {
    New-Item -ItemType Directory -Path $OutputDirectory -Force | Out-Null
}

$RollbackAuditLogPath = Join-Path $OutputDirectory "Rollback_AuditLog_$timestamp.csv"

Write-Host "==================================================================" -ForegroundColor Cyan
Write-Host " 21Vianet Intune Assignment Rollback / Restore Tool" -ForegroundColor Cyan
Write-Host " Backup Source   : $resolvedBackupPath" -ForegroundColor Cyan
Write-Host " ExecuteRollback : $ExecuteRollback $(if (-not $ExecuteRollback) { '(DRY-RUN MODE - NO CHANGES WILL BE MADE)' } else { '(LIVE ROLLBACK MODE)' })" -ForegroundColor $(if ($ExecuteRollback) { "Yellow" } else { "Green" })
Write-Host " OfflineDryRun   : $($OfflineDryRun.IsPresent)" -ForegroundColor Cyan
Write-Host "==================================================================" -ForegroundColor Cyan

if ($ExecuteRollback -and $OfflineDryRun.IsPresent) {
    throw "Cannot specify both -ExecuteRollback:`$true and -OfflineDryRun. OfflineDryRun is only for DryRun validation."
}

# Scan for JSON files (supports flat PreChange_Backup_* or nested Backup_JSON\<Category>\*.json)
$allJsonFiles = @(Get-ChildItem -Path $resolvedBackupPath -Filter "*.json" -File -Recurse | Sort-Object FullName)
if ($allJsonFiles.Count -eq 0) {
    Write-Warning "No .json backup files found in '$resolvedBackupPath'. Nothing to restore."
    return
}

# Filter and parse valid backup JSON files
$backupItems = New-Object System.Collections.Generic.List[object]
foreach ($file in $allJsonFiles) {
    try {
        # Fast path pre-filtering by file/folder name before reading large JSON bodies
        if ($FilterItemId.Count -gt 0) {
            $idMatchedInName = $false
            foreach ($fid in $FilterItemId) {
                if ($file.BaseName -match [regex]::Escape($fid)) {
                    $idMatchedInName = $true
                    break
                }
            }
            if (-not $idMatchedInName) { continue }
        }
        if ($FilterCategory.Count -gt 0) {
            $catMatchedInPath = $false
            foreach ($fcat in $FilterCategory) {
                if ($file.Directory.Name -ieq $fcat -or $file.BaseName -imatch "^$([regex]::Escape($fcat))_") {
                    $catMatchedInPath = $true
                    break
                }
            }
            if (-not $catMatchedInPath) { continue }
        }

        $rawContent = Get-Content -Path $file.FullName -Raw -Encoding UTF8
        $parsed = $rawContent | ConvertFrom-Json
        if ($null -eq $parsed.Category -or $null -eq $parsed.ItemId -or $null -eq $parsed.PSObject.Properties['Assignments']) {
            Write-Verbose "Skipping non-assignment JSON file: $($file.FullName)"
            continue
        }

        if ($FilterCategory.Count -gt 0 -and $parsed.Category -notin $FilterCategory) {
            continue
        }
        if ($FilterItemId.Count -gt 0 -and $parsed.ItemId -notin $FilterItemId) {
            continue
        }

        $backupItems.Add([PSCustomObject]@{
            BackupFile  = $file.FullName
            FileName    = $file.Name
            Category    = [string]$parsed.Category
            ItemId      = [string]$parsed.ItemId
            ItemName    = [string]$parsed.ItemName
            Timestamp   = if ($parsed.Timestamp) { [string]$parsed.Timestamp } elseif ($parsed.ExportedAtUtc) { [string]$parsed.ExportedAtUtc } else { "" }
            Assignments = @($parsed.Assignments)
        })
    }
    catch {
        Write-Warning "Failed to parse JSON file '$($file.FullName)': $($_.Exception.Message)"
    }
}

if ($backupItems.Count -eq 0) {
    Write-Warning "No matching Intune backup JSON items found after applying filters."
    return
}

Write-Host "[Found] $($backupItems.Count) backup item(s) ready for rollback processing." -ForegroundColor Green

# Connect to 21V Graph unless OfflineDryRun is set
if (-not $OfflineDryRun.IsPresent) {
    Initialize-21VGraphAuth -PlainToken $AccessToken -Tenant $TenantId -AppId $ClientId -Secret $ClientSecret
}
else {
    Write-Host "[OfflineDryRun] Skipping 21V Graph authentication. Validating backup schemas and building POST payloads locally..." -ForegroundColor Yellow
}

# ============================================================================
# 4. PROCESS ROLLBACK / RESTORE FOR EACH BACKUP ITEM
# ============================================================================
$auditLogs = New-Object System.Collections.Generic.List[object]

foreach ($item in $backupItems) {
    $cat      = $item.Category
    $itemId   = $item.ItemId
    $itemName = $item.ItemName
    $origAssignments = @($item.Assignments)

    Write-Host "`n------------------------------------------------------------------" -ForegroundColor DarkGray
    Write-Host "Processing [$cat] '$itemName' ($itemId)" -ForegroundColor White
    Write-Host "  Backup File : $($item.FileName)" -ForegroundColor Gray

    try {
        $epConfig  = Get-CategoryEndpointConfig -Category $cat
        $getUri    = [string]::Format($epConfig.GetAssignmentsUriTemplate, $itemId)
        $assignUri = [string]::Format($epConfig.AssignUriTemplate, $itemId)

        # Clean each assignment from the backup so it matches the exact Graph /assign POST schema
        $cleanAssignments = @()
        foreach ($a in $origAssignments) {
            if ($null -eq $a -or $null -eq $a.target) { continue }
            $cleanAssignments += (Format-AssignmentForPost -Category $cat -Assignment $a)
        }

        $bodyPayload = [ordered]@{
            $epConfig.AssignRootKey = @($cleanAssignments)
        }
        $jsonBody = $bodyPayload | ConvertTo-Json -Depth 15
        $restoreSummary = Get-AssignmentSummaryText -Assignments $cleanAssignments

        $liveCount = "N/A (Offline)"
        $liveSummary = "N/A (Offline)"

        if (-not $OfflineDryRun.IsPresent) {
            try {
                $liveResp = Invoke-21VGraphRequest -Uri $getUri -Method "GET"
                $liveArr = if ($null -ne $liveResp.value) { @($liveResp.value) } else { @() }
                $liveCount = $liveArr.Count
                $liveSummary = Get-AssignmentSummaryText -Assignments $liveArr
            }
            catch {
                $liveCount = "GET_Failed"
                $liveSummary = $_.Exception.Message
            }
        }

        Write-Host "  Current Live Assignments : $liveCount -> $liveSummary" -ForegroundColor DarkCyan
        Write-Host "  Restore Target Snapshot  : $($cleanAssignments.Count) -> $restoreSummary" -ForegroundColor Cyan

        if ($ExecuteRollback) {
            Write-Host "  [ROLLBACK] Posting original assignments to $assignUri ..." -ForegroundColor Yellow
            Invoke-21VGraphRequest -Uri $assignUri -Method "POST" -Body $jsonBody | Out-Null
            Write-Host "  [SUCCESS] Restored $($cleanAssignments.Count) assignment(s) for '$itemName'." -ForegroundColor Green
            $status = "Restored"
        }
        else {
            Write-Host "  [DRY-RUN] Would POST $($cleanAssignments.Count) assignment(s) to $assignUri" -ForegroundColor Green
            $status = "DryRun_ReadyToRestore"
        }

        $auditLogs.Add([PSCustomObject]@{
            Timestamp              = (Get-Date).ToUniversalTime().ToString("o")
            Category               = $cat
            ItemName               = $itemName
            ItemId                 = $itemId
            BackupFileName         = $item.FileName
            BackupTimestamp        = $item.Timestamp
            LiveAssignmentCount    = $liveCount
            LiveAssignmentsSummary = $liveSummary
            RestoredAssignmentCount= $cleanAssignments.Count
            RestoredSummary        = $restoreSummary
            AssignEndpoint         = $assignUri
            Status                 = $status
            PayloadJson            = ($bodyPayload | ConvertTo-Json -Depth 15 -Compress)
        })
    }
    catch {
        Write-Error "Failed to process rollback for [$cat] '$itemName' ($itemId): $($_.Exception.Message)" -ErrorAction Continue
        $auditLogs.Add([PSCustomObject]@{
            Timestamp              = (Get-Date).ToUniversalTime().ToString("o")
            Category               = $cat
            ItemName               = $itemName
            ItemId                 = $itemId
            BackupFileName         = $item.FileName
            BackupTimestamp        = $item.Timestamp
            LiveAssignmentCount    = "Error"
            LiveAssignmentsSummary = ""
            RestoredAssignmentCount= $origAssignments.Count
            RestoredSummary        = ""
            AssignEndpoint         = ""
            Status                 = "Error: $($_.Exception.Message)"
            PayloadJson            = ""
        })
    }
}

$auditLogs | Export-Csv -Path $RollbackAuditLogPath -NoTypeInformation -Encoding UTF8
Write-Host "`n==================================================================" -ForegroundColor Cyan
Write-Host " Rollback Processing Complete! Audit Log saved to:" -ForegroundColor Green
Write-Host " $RollbackAuditLogPath" -ForegroundColor White
Write-Host "==================================================================" -ForegroundColor Cyan

return $auditLogs
