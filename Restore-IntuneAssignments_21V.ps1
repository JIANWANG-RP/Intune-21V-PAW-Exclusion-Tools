.SYNOPSIS
    Restores (rolls back) Intune assignments in Azure China (21Vianet) from JSON backup files
    generated by Add-IntunePAWExclusion_21V.ps1 (PreChange_Backup_*) or Export-IntuneAssignments_21V.ps1 (Backup_JSON).

.DESCRIPTION
    1. Automatically installs/loads 'Microsoft.Graph.Authentication' and connects to 21V Graph
       (-Environment China), or runs offline payload verification when -OfflineDryRun is set.
    2. Scans the specified -BackupFolderPath for JSON backup files:
       - Supports Step 2 pre-change backups: PreChange_Backup_<timestamp>\<Category>_<ItemId>_Before.json
       - Supports Step 1 full export backups: Export_Output_<timestamp>\Backup_JSON\<Category>\*.json
    3. Reconstructs the exact Microsoft Graph '/assign' POST payload for all 10 Intune categories
       (App, AppConfig_ManagedDevice, AppConfig_ManagedApp, SettingsCatalog, DeviceConfig,
       AdminTemplate, CompliancePolicy, EndpointSecurity, PowerShellScript, ProactiveRemediation).
    4. Defaults to DryRun mode ($ExecuteRollback = $false) so you can preview what will be restored
       without modifying any live Intune configuration.
    5. When -ExecuteRollback:$true is specified, posts the original assignments back to Intune
       and writes a complete audit log CSV (Rollback_AuditLog_<timestamp>.csv).
