[CmdletBinding()]
param(
    [Parameter(Mandatory = $true, HelpMessage = "Path to PreChange_Backup_<timestamp> or Export_Output_<timestamp>\Backup_JSON")]
    [string]$BackupFolderPath,

    # Optional filter: only restore specific Category/Categories (e.g. 'SettingsCatalog', 'App')
    [Parameter(Mandatory = $false)]
    [string[]]$FilterCategory = @(),

    # Optional filter: only restore specific ItemId(s) (GUIDs) for targeted single-item rollback testing
    [Parameter(Mandatory = $false)]
    [string[]]$FilterItemId = @(),

    # SAFETY SWITCH: Defaults to $false (DryRun ONLY). Pass -ExecuteRollback (or -ExecuteRollback:$true) to actually POST rollback to Intune.
    [Parameter(Mandatory = $false)]
    [switch]$ExecuteRollback,

    # Offline DryRun mode: validates backup JSONs and builds '/assign' POST payloads without connecting to Graph
    [Parameter(Mandatory = $false)]
    [switch]$OfflineDryRun,

    # Optional custom output directory for Rollback Audit Log & DryRun payloads
    [Parameter(Mandatory = $false)]
    [string]$OutputDirectory = "",

    # Optional Service Principal (App-Only) or Interactive Auth Parameters for 21Vianet
    [Parameter(Mandatory = $false)]
    [string]$TenantId = "<YOUR-21V-TENANT-ID>",

    [Parameter(Mandatory = $false)]
    [string]$ClientId = "<YOUR-APP-CLIENT-ID>",

    [Parameter(Mandatory = $false)]
    [string]$ClientSecret = "",

    [Parameter(Mandatory = $false)]
    [switch]$UseInteractive,

    # Optional: Direct Bearer Access Token
    [Parameter(Mandatory = $false)]
    [string]$AccessToken = ""
)

$ErrorActionPreference = "Stop"

